"""The distribution files that make a package launchable with uv (specs/019-uvx-distribution).

`uvx --from <package directory or git reference> kaelen <verb>` builds the package with the pinned
backend named in `pyproject.toml`, which lays the whole package directory, unchanged, into the wheel
next to a second copy of `kaelen_launch.py` (contracts/distribution.md). The files are part of the
package and of its record, never content: no verb reads them.
"""

from __future__ import annotations

import re

from kaelen.outcome import Problem
from kaelen.package import location

COMMAND = "kaelen"
BACKEND = "hatchling==1.31.0"
GITATTRIBUTES = ".gitattributes"
PYPROJECT = "pyproject.toml"
LAUNCHER = "kaelen_launch.py"

# The version pattern of PEP 440, appendix B (research R-4).
_PEP440 = re.compile(
    r"""
    v?
    (?:
        (?:[0-9]+!)?
        [0-9]+(?:\.[0-9]+)*
        (?:[-_.]?(?:a|b|c|rc|alpha|beta|pre|preview)[-_.]?[0-9]*)?
        (?:-[0-9]+|[-_.]?(?:post|rev|r)[-_.]?[0-9]*)?
        (?:[-_.]?dev[-_.]?[0-9]*)?
    )
    (?:\+[a-z0-9]+(?:[-_.][a-z0-9]+)*)?
    """,
    re.VERBOSE | re.IGNORECASE,
)


def accepts(version: str) -> bool:
    """Whether uv can build a distribution with this version."""
    return _PEP440.fullmatch(version) is not None


def names(document: dict) -> dict:
    stem = f"{document['node']}_{document['capability']}".replace("-", "_")
    return {
        "distribution": f"kaelen-package-{document['node']}-{document['capability']}",
        "package": f"kaelen_package_{stem}",
        "launcher": f"kaelen_launch_{stem}",
    }


def launch(document: dict, uvx: bool) -> dict:
    """What the author needs to write the launch command (research R-7)."""
    return {
        "command": COMMAND,
        "subdirectory": location.relative(document["capability"]),
        "uvx": uvx,
    }


def files(document: dict) -> tuple[list[tuple[str, bytes]], list[Problem]]:
    """The distribution files of this package, sorted, and the findings about them."""
    out = [(GITATTRIBUTES, b"* -text\n")]
    version = document["version"]
    if not accepts(version):
        return out, [
            Problem(
                "uvx-version",
                "version",
                f"version {version!r} is not a version uv accepts (PEP 440): "
                "the package runs through run.py only",
            )
        ]
    n = names(document)
    out.append((PYPROJECT, _pyproject(document, n).encode("utf-8")))
    out.append((LAUNCHER, _launcher(n).encode("utf-8")))
    return sorted(out), []


def _pyproject(document: dict, n: dict) -> str:
    return f"""\
# Generated by kaelen package (specs/019-uvx-distribution/contracts/distribution.md).
[build-system]
requires = ["{BACKEND}"]
build-backend = "hatchling.build"

[project]
name = "{n["distribution"]}"
version = "{document["version"]}"
description = "Kaelen package {document["node"]}/{document["capability"]}"
requires-python = ">=3.11"

[project.scripts]
{COMMAND} = "{n["launcher"]}:main"

[tool.hatch.build.targets.wheel]
bypass-selection = true

[tool.hatch.build.targets.wheel.force-include]
"." = "{n["package"]}"
"{LAUNCHER}" = "{n["launcher"]}.py"
"""


def _launcher(n: dict) -> str:
    return f"""\
# Kaelen package entry for uv (specs/019-uvx-distribution/contracts/distribution.md).
# Imported from outside the package directory, it turns bytecode off before the package's
# run.py is imported, so nothing is ever written inside the package.
import sys

sys.dont_write_bytecode = True


def main():
    from {n["package"]}.run import main as run_main

    return run_main()
"""
